// 键后面加「#说明」区分（中文界面只显示 # 前面的部分）。浏览器与 Node 通用；Node 里默认中文。
// 不翻译的：钱包签名派生密钥的那条消息（wallet.js keyMessage）——改一个字派生出的密钥就变了，旧备份会解不开。

let lang = 'zh';
export const getLang = () => lang;
export function setLang(l) { lang = l === 'en' ? 'en' : 'zh'; }

/** 设置里的选择（'system' | 'zh' | 'en'）加上浏览器的语言偏好 → 实际使用的语言。
 *  跟随系统：偏好里先出现中文就用中文，先出现英文就用英文；都没有时用英文；拿不到偏好时用中文。 */
export function pickLang(setting, languages = []) {
  if (setting === 'zh' || setting === 'en') return setting;
  if (!languages.length) return 'zh';
  for (const l of languages) {
    if (/^zh\b/i.test(l)) return 'zh';
    if (/^en\b/i.test(l)) return 'en';
  }
  for (const l of languages) if (/^zh\b/i.test(l)) return 'zh';
  return 'en';
}

export function t(key, ...args) {
  const s = lang === 'en' && Object.prototype.hasOwnProperty.call(EN, key) ? EN[key] : key.split('#')[0];
  return args.length ? s.replace(/\{(\d+)\}/g, (m, i) => (i < args.length ? String(args[i]) : m)) : s;
}

